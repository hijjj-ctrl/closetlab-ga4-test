// 一覧用のサムネイル画像URL(動画記事はYouTubeのサムネイルを使用)
function journalThumbUrl(post) {
  return post.videoId
    ? "https://i.ytimg.com/vi/" + post.videoId + "/hqdefault.jpg"
    : post.image;
}
